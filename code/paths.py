"""Project layout.

    gomoku/
      app.py / app.bat     launcher: one click -> play UI
      ckpt/                model snapshots
        baseline0/         frozen baselines (manifest.json + model.pt)
        runs/<tag>/        training checkpoints
      data/                training data
        selfplay/          games generated by later-stage models
      code/                every script

All modules live in `code/`, so they resolve paths through this module rather
than through the current working directory. That way a script behaves the same
whether it is launched from the project root or from inside `code/`.
"""
from __future__ import annotations

from pathlib import Path

CODE = Path(__file__).resolve().parent
ROOT = CODE.parent
DATA = ROOT / "data"
CKPT = ROOT / "ckpt"
RUNS = CKPT / "runs"
BASELINES = CKPT
SELFPLAY = DATA / "selfplay"
WEB = CODE / "web"


def ensure() -> None:
    for p in (DATA, CKPT, RUNS, SELFPLAY):
        p.mkdir(parents=True, exist_ok=True)


def data(name: str) -> str:
    return str(DATA / name)


def run_dir(tag: str) -> str:
    d = RUNS / tag
    d.mkdir(parents=True, exist_ok=True)
    return str(d)


def run_ckpt(tag: str, name: str = "best.pt") -> str:
    return str(RUNS / tag / name)


def baseline_dir(bid: str) -> str:
    return str(BASELINES / bid)
